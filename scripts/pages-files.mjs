// Adds Cloudflare Pages' _headers (security headers, CSP) and _redirects
// (SPA fallback) to a production web build, after checking the build talks
// to the right API.
//
//   EXPO_PUBLIC_API_BASE_URL=https://api.example.com npm run build:web:pages
//   node scripts/pages-files.mjs apps/app/dist   (EXPO_PUBLIC_API_BASE_URL set)
//
// docs/DEPLOY.md, "Web app on Cloudflare Pages".
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const dir = resolve(process.argv[2] ?? 'apps/app/dist');
const apiBase = (process.env.EXPO_PUBLIC_API_BASE_URL ?? '').replace(/\/+$/, '');

function fail(msg) {
  console.error(`pages-files: ${msg}`);
  process.exit(1);
}

if (!existsSync(join(dir, 'index.html')))
  fail(`${dir}/index.html is missing; run npm run build:web first.`);
let api;
try {
  api = new URL(apiBase);
} catch {
  fail('set EXPO_PUBLIC_API_BASE_URL to the API origin, e.g. https://api.example.com');
}
if (api.protocol !== 'https:' || api.pathname !== '/') {
  fail(`EXPO_PUBLIC_API_BASE_URL must be an https origin without a path, got ${apiBase}`);
}

// The URL is inlined at build time; a stale Metro cache can leave it out.
function* files(d) {
  for (const entry of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, entry.name);
    if (entry.isDirectory()) yield* files(p);
    else yield p;
  }
}
const bundles = [...files(dir)].filter((f) => f.endsWith('.js') && statSync(f).isFile());
if (!bundles.some((f) => readFileSync(f, 'utf8').includes(api.origin))) {
  fail(
    `no bundle in ${dir} contains ${api.origin}: rebuild with EXPO_PUBLIC_API_BASE_URL set (npm run build:web).`,
  );
}

const wsOrigin = `wss://${api.host}`;
// react-native-web injects <style> elements and inline styles, so styles
// need 'unsafe-inline'; scripts do not (one external, hashed bundle).
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self' ${api.origin} ${wsOrigin}`,
  "manifest-src 'self'",
  "worker-src 'self'", // the Web Push service worker (/push/sw.js)
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/pages-files.mjs; Cloudflare Pages reads it.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()

/_expo/static/*
  Cache-Control: public, max-age=31536000, immutable

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;

// Client-side routing: every unknown path serves index.html with a 200.
const redirects = `# Generated by scripts/pages-files.mjs: single-page app fallback.
/* /index.html 200
`;

writeFileSync(join(dir, '_headers'), headers);
writeFileSync(join(dir, '_redirects'), redirects);
console.log(`pages-files: wrote _headers and _redirects for API ${api.origin} into ${dir}`);
